import { ref } from 'vue'
import { isAccountMode } from './runtime'

// 轻量国际化：不引入 vue-i18n，本站文案结构简单，
// 一个响应式 locale + 平铺字典足够，且能完全控制中英文措辞。
const STORAGE_KEY = 'lmfpd_locale'
export const SUPPORTED = ['zh', 'en']

function readInitial() {
  try {
    const v = isAccountMode() ? localStorage.getItem(STORAGE_KEY) : null
    if (SUPPORTED.includes(v)) return v
  } catch { /* 隐私模式下忽略 */ }
  // 未显式选择时跟随浏览器语言
  const nav = (navigator.language || '').toLowerCase()
  return nav.startsWith('zh') ? 'zh' : 'en'
}

export const locale = ref(readInitial())

export function setLocale(l) {
  const next = SUPPORTED.includes(l) ? l : 'zh'
  locale.value = next
  document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
  try { if (isAccountMode()) localStorage.setItem(STORAGE_KEY, next) } catch { /* 忽略 */ }
}

export function toggleLocale() {
  setLocale(locale.value === 'zh' ? 'en' : 'zh')
}

export function initLocale() {
  setLocale(readInitial())
}

/** 取词；支持 {name} 形式的占位符 */
export function t(key, params) {
  const dict = messages[locale.value] || messages.zh
  let s = dict[key] ?? messages.zh[key] ?? key
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m))
  }
  return s
}

